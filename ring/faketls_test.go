package ring

import (
	"crypto/ed25519"
	"crypto/rand"
	"crypto/tls"
	"crypto/x509"
	"crypto/x509/pkix"
	"math/big"
	"testing"
	"time"

	"github.com/hoarddb/hoarddb-go/hoarddbwire/trust"
)

// fakeServerTLS is the TLS configuration of the fake server: a self-signed ed25519
// certificate made for this test, as a node makes its own when it starts, and the
// fingerprint a client pins to trust it. Nothing is written to disk.
func fakeServerTLS(t *testing.T) (*tls.Config, string) {
	t.Helper()
	public, private, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		t.Fatal(err)
	}
	template := &x509.Certificate{
		SerialNumber: big.NewInt(1),
		Subject:      pkix.Name{CommonName: "ring fake server"},
		NotBefore:    time.Now().Add(-time.Hour),
		NotAfter:     time.Now().Add(time.Hour),
		KeyUsage:     x509.KeyUsageDigitalSignature,
		ExtKeyUsage:  []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
	}
	der, err := x509.CreateCertificate(rand.Reader, template, template, public, private)
	if err != nil {
		t.Fatal(err)
	}
	config := &tls.Config{
		MinVersion:   tls.VersionTLS13,
		NextProtos:   []string{trust.ALPN},
		Certificates: []tls.Certificate{{Certificate: [][]byte{der}, PrivateKey: private}},
	}
	return config, trust.Fingerprint(public)
}
